#!/usr/bin/env python3
"""Step 5 reference-only reward/weight diagnostic (NO MuJoCo model needed).

Reuses the 944-reference 23,600-sample RAW observation archive generated by
Step 4. This is a nominal, imposed-kinematics baseline, NOT a physics rollout.

Usage:
python inspect_reference_rewards.py --samples C:\\Users\\BoussofaraS\\Documents\\residuals\\RL_myosuite2\\tests\\observation_range_report\\observation_samples.npz --normalization C:\\Users\\BoussofaraS\\Documents\\residuals\\RL_myosuite2\\normalization_parameters\\observation_normalization_refined_944.json --output reward_reference_report
"""
from __future__ import annotations
import argparse, csv, json
from pathlib import Path
import numpy as np

import sys
sys.path.append(str(Path(__file__).resolve().parent.parent))
from rewards import RewardConfig, quat_rotate


def summarize(values: np.ndarray) -> dict[str, float]:
    a=np.asarray(values,float)
    return {k: float(v) for k,v in zip(('min','p01','p05','median','mean','p95','p99','max'),
                (*np.percentile(a,[0,1,5,50]), float(np.mean(a)),*np.percentile(a,[95,99,100])))}


def inspect(samples: Path, normalization_file: Path, output: Path,
            config: RewardConfig = RewardConfig(), *, plot: bool=True) -> dict:
    output.mkdir(parents=True, exist_ok=True)
    settings=json.loads(normalization_file.read_text(encoding='utf-8'))
    if settings['format_version'] != 1 or settings['reference_count'] != 944 or settings['sample_count'] != 23600:
        raise ValueError('Expected fixed normalization fitted on final 944-reference library')
    block = {k: slice(int(a),int(b)) for k,(a,b) in settings['block_slices'].items()}
    with np.load(samples,allow_pickle=False) as file:
        o=np.asarray(file['observations'],dtype=np.float64)
        names=np.asarray(file['feature_names'])
        refs=np.asarray(file['reference_ids'],dtype=int)
        paths=np.asarray(file['reference_paths'])
        phases=np.asarray(file['phases'])
    if o.shape != (23600,485) or len(paths) != 944 or len(names) != o.shape[1]:
        raise ValueError('Unexpected observation archive (must be RAW 485-D and 944 references)')
    if not np.array_equal(names, np.asarray(settings['feature_names'])):
        raise ValueError('Observation column names/order differ from fitted Step-4 normalizer')
    if not np.isfinite(o).all():
        raise FloatingPointError('Nonfinite reference observations')

    j=o[:,block['joint_proprioception']]
    jref=o[:,block['reference_joints']]
    a=o[:,block['actual_sites']]
    b=o[:,block['reference_sites']]
    mus=o[:,block['muscle_activations']]
    root=o[:,block['root_state']]
    gait=o[:,block['gait_phase']]
    N=len(o)
    errors={
        'joint_position': np.mean((j[:,:28]-jref)**2,axis=1),
        # Actual qvel was initialized from the stored reference at the nominal
        # phase rate during this imposed replay, so its target is itself.
        'joint_velocity': np.zeros(N),
        'site_position': np.mean(np.sum((a[:,:18]-b[:,:18]).reshape(-1,6,3)**2,axis=2),axis=1),
        'site_linear_velocity': np.mean(np.sum((a[:,18:36]-b[:,18:36]).reshape(-1,6,3)**2,axis=2),axis=1),
        'site_angular_velocity': np.mean(np.sum((a[:,68:92]-b[:,68:92]).reshape(-1,8,3)**2,axis=2),axis=1),
    }
    aq=a[:,36:68].reshape(-1,8,4)
    bq=b[:,36:68].reshape(-1,8,4)
    aq=aq/np.maximum(np.linalg.norm(aq,axis=2,keepdims=True),1e-12)
    bq=bq/np.maximum(np.linalg.norm(bq,axis=2,keepdims=True),1e-12)
    theta=2*np.arccos(np.clip(np.abs(np.sum(aq*bq,axis=2)),0,1))
    errors['site_orientation']=np.mean(theta**2,axis=1)

    local=root[:,5:8]
    world=quat_rotate(root[:,1:5], local)
    # All references in this prepared library were heading-aligned to +Y.
    # Without per-reference root_displacement vectors in the saved NPZ we can
    # only estimate the speed term; online reward computes travel-direction
    # projection from each reference's actual root displacement.
    speed=world[:,1]
    desired=gait[:,0]
    speed_err=speed-desired
    # Pelvis local +Y is world-up for healthy MyoLeg gait. For scalar-first
    # quaternion R[2,1] = 2*(q_y*q_z + q_x*q_w).
    upright_dot=np.clip(2*(root[:,3]*root[:,4]+root[:,2]*root[:,1]),-1,1)

    scores={k:np.exp(-getattr(config,'beta_'+k)*e) for k,e in errors.items()}
    scores['speed']=np.exp(-config.beta_speed*speed_err**2)
    scores['upright']=np.exp(-config.beta_upright*(1-upright_dot))
    # The lookup contains mapped muscle activations only. The 10 unmapped
    # muscle states are set to 0 in the default mode, but L1/L2 divide by 80.
    costs={
       'activation_l1': np.sum(np.abs(mus),axis=1)/80.,
       'activation_l2': np.sum(mus**2,axis=1)/80.,
       'residual': np.zeros(N),
       'phase': np.zeros(N),
    }
    contrib={k: scores[k]*getattr(config,'w_'+k) for k in scores}
    penalties={k:costs[k]*getattr(config,'lambda_'+k) for k in costs}
    total=sum(contrib.values())-sum(penalties.values())
    columns={
        'reference_id':refs,'phase':phases, 'reward_nominal': total,
        'speed_y_proxy_m_s': speed,'desired_speed_m_s':desired,
        'speed_error_y_proxy_m_s':speed_err,'upright_dot':upright_dot,
    }
    columns.update({f'error_{k}':v for k,v in errors.items()})
    columns.update({f'score_{k}':v for k,v in scores.items()})
    columns.update({f'cost_{k}':v for k,v in costs.items()})
    columns.update({f'contribution_{k}':v for k,v in contrib.items()})
    columns.update({f'penalty_{k}':v for k,v in penalties.items()})
    fields=list(columns)
    with (output/'reference_reward_samples.csv').open('w',newline='',encoding='utf-8') as f:
        w=csv.writer(f);w.writerow(fields)
        for row in zip(*[columns[k] for k in fields]):w.writerow(row)

    group_fields=['reward_nominal',*[f'score_{k}' for k in scores],
                  'cost_activation_l1','cost_activation_l2','speed_error_y_proxy_m_s']
    with (output/'per_reference_reward_summary.csv').open('w',newline='',encoding='utf-8') as f:
        w=csv.writer(f);w.writerow(['relative_reference','count', *[f'{k}_{stat}' for k in group_fields for stat in ('mean','min','p05','p95')]])
        for ri,path in enumerate(paths):
            mask=refs==ri
            vals=[]
            for k in group_fields:
                x=columns[k][mask]
                vals += [float(np.mean(x)),float(np.min(x)),float(np.percentile(x,5)),float(np.percentile(x,95))]
            w.writerow([path,int(mask.sum()),*vals])

    # Physical half-score targets are interpretable even when replay is perfect.
    half_values={
        'joint_position': ('joint RMS', 'rad',.15),
        'joint_velocity': ('joint RMS','rad/s',2.),
        'site_position': ('site Euclidean RMS','m',.12),
        'site_orientation': ('site RMS','rad',.3),
        'site_linear_velocity': ('site Euclidean RMS','m/s',1.5),
        'site_angular_velocity': ('site Euclidean RMS','rad/s',3.),
        'speed': ('signed speed difference','m/s',.35),
        'upright': ('tilt angle','degrees',18.),
    }
    with (output/'weight_sensitivity.csv').open('w',newline='',encoding='utf-8') as f:
        w=csv.writer(f);w.writerow(['term','perturbation','units','score','weighted_contribution','interpretation'])
        for k,(interpret,unit,half) in half_values.items():
            for factor in (0,.5,1,2):
                physical=factor*half
                if k=='upright':score=np.exp(-config.beta_upright*(1-np.cos(np.deg2rad(physical))))
                else:score=np.exp(-getattr(config,'beta_'+k)*physical**2)
                w.writerow([k,physical,unit,float(score),float(score*getattr(config,'w_'+k)),interpret])

    report={
       'source':'offline inspection of RAW Step-4 imposed reference poses; not an RL rollout',
       'references':int(len(paths)), 'samples':int(N),
       'nominal_policy_action':'zero muscle residual, zero RL phase rate',
       'reference_velocity_target':'identical to imposed qvel under nominal phase rate (no perturbation)',
       'activation_source':'periodic RSI lookup, 70 mapped; 10 disabled zero; L1/L2 divided by 80',
       'speed_approximation':'world +Y reconstructed from local pelvis velocity (confirmed by sample reference stride displacement); online reward uses per-reference stride direction',
       'inaccessible_from_reference_only':['gait recovery/late falls','policy residual behavior','dynamic activation responses','event/phase correction','non-reference contact forces','true site errors after policy deviates'],
       'warning':'Scores near 1 on imposed trajectories DO NOT validate reward temperatures or weight priorities. Review the synthetic sensitivity table and run dynamic rollouts after implementing policy.',
       'calibration_config':{k:v for k,v in vars(config).items() if not isinstance(v, np.ndarray)},
       'summary':{k:summarize(v) for k,v in columns.items() if k != 'reference_id' and k != 'phase'},
    }
    (output/'reward_reference_baseline.json').write_text(json.dumps(report,indent=2),encoding='utf-8')

    if plot:
        try:
            import matplotlib.pyplot as plt
        except ImportError:
            pass
        else:
            chosen=['reward_nominal','score_site_position','score_site_linear_velocity',
                    'score_site_orientation','score_speed','score_upright',
                    'cost_activation_l1','cost_activation_l2']
            fig,axs=plt.subplots(4,2,figsize=(12,13))
            for ax,k in zip(axs.flat,chosen):
                ax.hist(columns[k],bins=65)
                ax.set_title(k);ax.set_ylabel('Reference phase samples')
            fig.suptitle('Reference-only reward baseline: 944 refined cycles / 23,600 poses')
            fig.tight_layout();fig.savefig(output/'reward_distributions.png',dpi=170)
            plt.close(fig)
    return report


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--samples',type=Path,required=True)
    p.add_argument('--normalization',type=Path,required=True)
    p.add_argument('--output',type=Path,default=Path('reward_reference_report'))
    p.add_argument('--no-plots',action='store_true')
    p.add_argument('--reward-config',type=Path,default=None,help='Optional JSON of RewardConfig fields')
    a=p.parse_args()
    config=RewardConfig(**json.loads(a.reward_config.read_text(encoding='utf-8'))) if a.reward_config else RewardConfig()
    result=inspect(a.samples,a.normalization,a.output,config=config,plot=not a.no_plots)
    print(f"Reference-only reward check: {result['references']} references, {result['samples']} poses")
    for k in ('reward_nominal','score_site_position','score_site_linear_velocity','score_speed','score_upright','cost_activation_l1','cost_activation_l2'):
        x=result['summary'][k]
        print(f'  {k:<29} mean={x["mean"]:.4f} P05={x["p05"]:.4f} P95={x["p95"]:.4f}')
    print(f'Wrote {a.output.resolve()}')

if __name__=='__main__':main()
