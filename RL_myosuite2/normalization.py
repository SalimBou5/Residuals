"""Fixed, inspectable MyoLeg observation normalization (no running statistics).

The fitted centers/scales describe healthy gait, NOT hard physical bounds.
Only kinematic/speed channels get a robust affine transform; muscle channels,
quaternions and phase trigonometry retain their physical representations.
The 4 raw touch-force values are compressed by asinh(F/200 N).

A versioned JSON parameter file is generated by fit_observation_normalization.py.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Mapping, Sequence

import numpy as np


class FixedObservationNormalizer:
    VERSION = 1

    def __init__(self, settings: Mapping):
        if int(settings.get('format_version', -1)) != self.VERSION:
            raise ValueError('Unsupported observation normalizer format version')
        self.feature_names = tuple(settings['feature_names'])
        self.dimension = len(self.feature_names)
        self.center = np.asarray(settings['center'], dtype=np.float64)
        self.scale = np.asarray(settings['scale'], dtype=np.float64)
        self.modes = np.asarray(settings['mode'], dtype=str)
        self.clip = float(settings['clip'])
        self.force_scale_n = float(settings['force_scale_n'])
        self.observed_muscles = tuple(settings['observed_muscles'])
        self.lookahead_seconds = tuple(float(x) for x in settings['lookahead_seconds'])
        self.block_slices = dict(settings['block_slices'])
        self.settings = dict(settings)
        self.last_clipped_count = 0
        self.last_clipped_indices = np.empty(0, dtype=np.int64)
        self.total_clipped = 0
        self.calls = 0
        if (self.center.shape != (self.dimension,) or self.scale.shape != (self.dimension,) or
                self.modes.shape != (self.dimension,)):
            raise ValueError('Invalid center/scale/mode vector length')
        if not np.isfinite(self.clip) or self.clip <= 0 or not np.isfinite(self.force_scale_n) or self.force_scale_n <= 0:
            raise ValueError('Invalid clip or force scale')
        if not (np.isfinite(self.center).all() and np.isfinite(self.scale).all() and (self.scale > 0).all()):
            raise ValueError('All center and scale values must be finite, scales positive')
        if not set(self.modes).issubset({'affine', 'identity', 'force_asinh'}):
            raise ValueError('Unknown observation normalizer mode')
        if int(np.count_nonzero(self.modes == 'force_asinh')) != 4:
            raise ValueError('Exactly four force channels are required')

    @classmethod
    def load(cls, path: str | Path, *, expected_dimension: int | None = None,
             observed_muscles: Sequence[str] | None = None,
             lookahead_seconds: Sequence[float] | None = None,
             expected_slices: Mapping | None = None) -> 'FixedObservationNormalizer':
        with Path(path).open('r', encoding='utf-8') as f:
            settings = json.load(f)
        obj = cls(settings)
        if expected_dimension is not None and obj.dimension != expected_dimension:
            raise ValueError(f'Normalizer expects {obj.dimension} observations, environment has {expected_dimension}. '
                             'Regenerate the normalizer for the selected enable_unmapped mode.')
        if observed_muscles is not None and tuple(observed_muscles) != obj.observed_muscles:
            raise ValueError('Normalizer muscle names/order do not match this MyoLeg model/mask')
        if lookahead_seconds is not None and not np.allclose(list(lookahead_seconds), obj.lookahead_seconds,
                                                            atol=1e-10, rtol=0):
            raise ValueError('Normalizer lookahead times do not match environment')
        if expected_slices is not None:
            current = {k: [int(v.start), int(v.stop)] for k, v in expected_slices.items()}
            if current != obj.block_slices:
                raise ValueError('Normalizer observation block layout does not match environment')
        return obj

    def transform(self, raw: np.ndarray) -> np.ndarray:
        x = np.asarray(raw, dtype=np.float64)
        if x.shape != (self.dimension,) or not np.isfinite(x).all():
            raise ValueError('Observation vector shape mismatch or contains nonfinite values')
        y = x.copy()
        affine = self.modes == 'affine'
        forces = self.modes == 'force_asinh'
        y[affine] = (x[affine] - self.center[affine]) / self.scale[affine]
        # Only nonnegative touch sensor forces are physical; small numerical noise is zeroed.
        if np.any(x[forces] < -1e-6):
            raise ValueError('Negative touch force in normalized observation')
        y[forces] = np.arcsinh(np.maximum(x[forces], 0.0) / self.force_scale_n)
        # Clipping is a safety net for very extreme/unstable states, not a range
        # inferred from healthy reference data. Monitor its frequency during PPO.
        self.last_clipped_indices = np.flatnonzero((self.modes != 'identity') & (np.abs(y) > self.clip))
        self.last_clipped_count = len(self.last_clipped_indices)
        self.total_clipped += self.last_clipped_count
        self.calls += 1
        non_identity = self.modes != 'identity'
        y[non_identity] = np.clip(y[non_identity], -self.clip, self.clip)
        return y.astype(np.float32)

    @property
    def saturation_fraction(self) -> float:
        return float(self.total_clipped / (self.dimension * self.calls)) if self.calls else 0.0
